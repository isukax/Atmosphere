"""Regenerate the embedded Hillaire2020/C+A+B data using Python's standard library."""
from pathlib import Path
import hashlib
import json
import math
import struct

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'data/hillaire_cab.json'
data = json.loads(source.read_text(encoding='utf-8'))
component = data['preset']['components'][0]
def f32(x): return struct.unpack('f', struct.pack('f', x))[0]
def literal(x): return format(f32(x), '.9e') + 'f'
def vector(v): return '{' + ', '.join(literal(x) for x in v) + '}'
table = [[f32(x) for x in row] for row in component['phase']['values_rgb']]
# Match legendreMomentsTable: float input, double accumulation, 64 midpoints per interval.
moments = [[0.0]*3 for _ in range(3)]
intervals = len(table)-1
du = 1.0/(intervals*64)
for i in range(intervals):
    for k in range(64):
        f = (k+0.5)/64
        u = (i+f)*(1.0/intervals)
        mu = math.cos(math.pi*u*u)
        weight = 2*math.pi*math.sin(math.pi*u*u)*2*math.pi*u*du
        legendre = (1.0, mu, 0.5*(3*mu*mu-1))
        for c in range(3):
            p = (1-f)*table[i][c]+f*table[i+1][c]
            for l in range(3): moments[l][c] += p*legendre[l]*weight
lines = ['#pragma once', '// Generated by tools/generate_data.py; do not edit.',
         '// Source SHA256: '+hashlib.sha256(source.read_bytes()).hexdigest(),
         'namespace compact::atmosphere::fixed {']
for name, values in [('rayleigh', data['rayleigh_scattering_per_km']),
                     ('ozone', data['ozone_absorption_per_km']),
                     ('sunColor', data['sun_color']),
                     ('mieScattering', component['scattering_per_km']),
                     ('mieAbsorption', component['absorption_per_km'])]:
    lines.append('inline constexpr float '+name+'[3] = '+vector(values)+';')
lines.append('inline constexpr float solarLux = '+literal(data['solar_illuminance_lux_from_spectrum'])+';')
lines.append('inline constexpr float moments[3][4] = {'+', '.join(vector(row+[0]) for row in moments)+'};')
lines.append('inline constexpr float phase[2049][4] = {')
lines.extend('    '+vector(row+[0])+',' for row in table)
lines.extend(['};', '}'])
(ROOT/'src/atmosphere/FixedData.h').write_text('\n'.join(lines)+'\n', encoding='utf-8', newline='\n')
